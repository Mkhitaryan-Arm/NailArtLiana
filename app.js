const $ = id => document.getElementById(id);

let lang = "hy";
let selectedTime = "";
let loadingSlots = false;
let services = [];

const form = $("bookingForm");
const dateInput = $("date");
const timeInput = $("time");
const slotsContainer = $("slots");
const selectedTimeBox = $("selectedTime");
const messageBox = $("message");
const submitButton = document.querySelector(".submit-btn");

function todayLocal() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");

  return `${year}-${month}-${day}`;
}

dateInput.min = todayLocal();

function setMessage(text, type = "") {
  messageBox.textContent = text;
  messageBox.className = `message ${type}`;
}

function getServiceName(service) {
  if (lang === "ru") {
    return service.nameRu || service.name;
  }

  if (lang === "en") {
    return service.nameEn || service.name;
  }

  return service.nameHy || service.name;
}

function getServiceDescription(service) {
  if (lang === "ru") {
    return service.descriptionRu || service.description || "";
  }

  if (lang === "en") {
    return service.descriptionEn || service.description || "";
  }

  return service.descriptionHy || service.description || "";
}

function formatPrice(price) {
  if (price === null || price === undefined || price === "") {
    return translations[lang].priceContact;
  }

  const formatted = Number(price).toLocaleString(
    lang === "hy" ? "hy-AM" : lang === "ru" ? "ru-RU" : "en-US"
  );

  return `${translations[lang].priceFrom} ${formatted} ${translations[lang].dram}`;
}

function renderServices() {
  const serviceSelect = $("service");
  const servicesGrid = document.querySelector(".service-grid");

  if (!serviceSelect) return;

  // Գրանցման ցանկ
  serviceSelect.innerHTML = "";

  const placeholder = document.createElement("option");
  placeholder.value = "";
  placeholder.textContent = translations[lang].chooseService;
  serviceSelect.appendChild(placeholder);

  services.forEach(service => {
    const option = document.createElement("option");
    option.value = service.id;
    option.textContent = `${getServiceName(service)} — ${formatPrice(service.price)}`;
    serviceSelect.appendChild(option);
  });

  // Ծառայությունների քարտեր
  if (!servicesGrid) return;

  servicesGrid.innerHTML = "";

  if (services.length === 0) {
    const empty = document.createElement("p");
    empty.className = "hint";
    empty.textContent = translations[lang].noServices;
    servicesGrid.appendChild(empty);
    return;
  }

  services.forEach((service, index) => {
    const card = document.createElement("article");
    card.className = "service-card";

    const imageBox = document.createElement("div");
    imageBox.className = "service-image";

    // Հին ծառայությունների նկարների դասերը պահպանում ենք
    if (service.id === "manicure") {
      imageBox.classList.add("service-image-1");
    } else if (service.id === "gel") {
      imageBox.classList.add("service-image-2");
    } else if (service.id === "extension") {
      imageBox.classList.add("service-image-3");
    } else {
      imageBox.classList.add("service-image-default");
    }

    const content = document.createElement("div");
    content.className = "service-content";

    const number = document.createElement("span");
    number.className = "service-number";
    number.textContent = String(index + 1).padStart(2, "0");

    const title = document.createElement("h3");
    title.textContent = getServiceName(service);

    const description = document.createElement("p");
    description.textContent = getServiceDescription(service);

    const price = document.createElement("div");
    price.className = "service-price";
    price.textContent = formatPrice(service.price);

    content.append(number, title, description, price);
    card.append(imageBox, content);
    servicesGrid.appendChild(card);
  });
}

async function loadServices() {
  try {
    const response = await fetch("/api/services");
    const data = await response.json();

    if (!response.ok) {
      throw new Error(data.error || "Services error");
    }

    services = Array.isArray(data) ? data : data.services || [];
    renderServices();
  } catch (error) {
    console.error("Services loading error:", error);

    services = [];
    renderServices();
  }
}

function setLanguage(next) {
  lang = translations[next] ? next : "hy";
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (translations[lang][key]) {
      element.innerHTML = translations[lang][key];
    }
  });

  $("name").placeholder =
    lang === "hy" ? "Անուն Ազգանուն" :
    lang === "ru" ? "Имя Фамилия" : "Full name";

  $("phone").placeholder = "+374 ...";

  renderServices();

  if (dateInput.value) {
    loadSlots();
  } else {
    selectedTimeBox.textContent = translations[lang].chooseTime;
    slotsContainer.innerHTML =
      `<p class="hint">${translations[lang].selectDate}</p>`;
  }
}

$("language").addEventListener("change", event => {
  setLanguage(event.target.value);
});

function resetSelectedTime() {
  selectedTime = "";
  timeInput.value = "";
  selectedTimeBox.textContent = translations[lang].chooseTime;
}

function renderSlots(slots) {
  slotsContainer.innerHTML = "";

  const availableSlots = slots.filter(slot => slot.available);

  if (availableSlots.length === 0) {
    slotsContainer.innerHTML =
      `<p class="hint">${translations[lang].noSlots}</p>`;
    return;
  }

  slots.forEach(slot => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "slot";

    const timeText = document.createElement("span");
    timeText.textContent = slot.time;
    button.appendChild(timeText);

    if (!slot.available) {
      button.disabled = true;

      const small = document.createElement("small");

      if (slot.reason === "booked") {
        small.textContent = translations[lang].busy;
      } else if (slot.reason === "blocked") {
        small.textContent = translations[lang].blocked;
      } else {
        small.textContent = translations[lang].past;
      }

      button.appendChild(small);
      button.classList.add("unavailable");
    } else {
      button.addEventListener("click", () => {
        document.querySelectorAll(".slot").forEach(item => {
          item.classList.remove("selected");
        });

        button.classList.add("selected");
        selectedTime = slot.time;
        timeInput.value = slot.time;
        selectedTimeBox.textContent = slot.time;
        setMessage("");
      });
    }

    slotsContainer.appendChild(button);
  });
}

async function loadSlots() {
  if (!dateInput.value) return;

  resetSelectedTime();
  loadingSlots = true;

  slotsContainer.innerHTML =
    `<p class="hint">${translations[lang].sending}</p>`;

  try {
    const response = await fetch(
      `/api/slots?date=${encodeURIComponent(dateInput.value)}`
    );

    const data = await response.json();

    if (!response.ok) {
      throw new Error(data.error || "Slots error");
    }

    renderSlots(data.slots);
  } catch (error) {
    slotsContainer.innerHTML =
      `<p class="hint">${translations[lang].loadError}</p>`;
  } finally {
    loadingSlots = false;
  }
}

dateInput.addEventListener("change", () => {
  setMessage("");
  loadSlots();
});

form.addEventListener("submit", async event => {
  event.preventDefault();

  if (loadingSlots) return;

  const name = $("name").value.trim();
  const phone = $("phone").value.trim();
  const service = $("service").value;
  const date = dateInput.value;
  const time = timeInput.value;

  if (!name || !phone || !service || !date || !time) {
    setMessage(translations[lang].fill, "error");
    return;
  }

  submitButton.disabled = true;
  submitButton.querySelector("span").textContent =
    translations[lang].sending;

  try {
    const response = await fetch("/api/bookings", {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        name,
        phone,
        service,
        date,
        time,
        language: lang
      })
    });

    const data = await response.json();

    if (response.status === 409) {
      setMessage(translations[lang].conflict, "error");
      await loadSlots();
      return;
    }

    if (!response.ok) {
      throw new Error(data.error || "Booking error");
    }

    form.reset();
    dateInput.min = todayLocal();
    resetSelectedTime();

    slotsContainer.innerHTML =
      `<p class="hint">${translations[lang].selectDate}</p>`;

    setMessage(translations[lang].success, "success");
  } catch (error) {
    setMessage(
      error.message || translations[lang].error,
      "error"
    );
  } finally {
    submitButton.disabled = false;
    submitButton.querySelector("span").textContent =
      translations[lang].submit;
  }
});

// Սկզբնական բեռնում
setLanguage("hy");
loadServices();
